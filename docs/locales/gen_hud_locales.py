"""Builds ControllerCam_HUD/Locales.lua from the English texts found in the HUD's code (extract_hud.py) and the
translations in docs/locales/hud/<locale>.txt (one text per line, in the order of hud/enUS.txt).

    python docs/locales/gen_hud_locales.py            write hud/enUS.txt (if the code changed) and Locales.lua
    python docs/locales/gen_hud_locales.py --check    only report problems
"""
import os
import re
import sys

import extract_hud

HERE = os.path.dirname(os.path.abspath(__file__))
HUD = os.path.join(HERE, "hud")
OUT = os.path.join(HERE, "..", "..", "ControllerCam_HUD", "Locales.lua")
LOCALES = ["deDE", "esES", "frFR", "itIT", "koKR", "ptBR", "ruRU", "zhCN", "zhTW"]
PLACEHOLDER = re.compile(r"%[-.\d]*[sd]|%%|\\n")


def read(name):
    path = os.path.join(HUD, name + ".txt")
    if not os.path.isfile(path):
        return None
    return open(path, encoding="utf-8").read().split("\n")[:-1] if open(path, encoding="utf-8").read().endswith("\n") \
        else open(path, encoding="utf-8").read().split("\n")


def quote(text):
    # the texts are Lua string contents already (\n stays an escape); only a bare double quote needs escaping
    return '"' + re.sub(r'(?<!\\)"', r'\\"', text) + '"'


def main(check_only):
    english = extract_hud.keys()
    problems = []
    saved = read("enUS")
    if saved != english:
        if check_only:
            problems.append("hud/enUS.txt is out of date: the texts in the code changed")
        else:
            open(os.path.join(HUD, "enUS.txt"), "w", encoding="utf-8", newline="\n").write("\n".join(english) + "\n")
    tables = {}
    for loc in LOCALES:
        lines = read(loc)
        if lines is None:
            problems.append("%s: no translation file" % loc)
            continue
        if len(lines) != len(english):
            problems.append("%s: %d lines, expected %d" % (loc, len(lines), len(english)))
            continue
        for i, (en, tr) in enumerate(zip(english, lines), 1):
            if not tr.strip():
                problems.append("%s line %d: empty" % (loc, i))
            if PLACEHOLDER.findall(tr) != PLACEHOLDER.findall(en):
                problems.append("%s line %d: placeholders differ: %s" % (loc, i, en))
            if re.search(r"\\(?!n)", tr):
                problems.append("%s line %d: stray backslash" % (loc, i))
        tables[loc] = lines
    for p in problems:
        print("PROBLEM", p)
    if check_only or problems:
        print("english %d, locales %d, problems %d" % (len(english), len(tables), len(problems)))
        return 1 if problems else 0

    out = ['''-- ControllerCam HUD localization. GENERATED by docs/locales/gen_hud_locales.py: edit the translation files in
-- docs/locales/hud and run it again.
--
-- The English text is the lookup key (L["Some text"]). Translations are listed in the same order as ENGLISH,
-- one table per game locale. Anything missing falls back to English.

local ADDON, ns = ...

local ENGLISH = {''']
    for i, k in enumerate(english, 1):
        out.append("    %s,  -- %d" % (quote(k), i))
    out.append("}\n")
    out.append("local TRANSLATIONS = {")
    for loc in LOCALES:
        out.append("    %s = {" % loc)
        for i, t in enumerate(tables[loc], 1):
            out.append("        %s,  -- %d" % (quote(t), i))
        out.append("    },")
    out.append("}")
    out.append("TRANSLATIONS.esMX = TRANSLATIONS.esES      -- Latin American Spanish uses the same text")
    out.append('''
-- Lookup table: L["English text"] -> translated text, or the English text itself when there is none.
local L = setmetatable({}, { __index = function(_, key) return key end })

local translated = TRANSLATIONS[GetLocale()]
if translated then
    for i, english in ipairs(ENGLISH) do
        if translated[i] then L[english] = translated[i] end
    end
end

ns.L = L
ns.localeData = { english = ENGLISH, translations = TRANSLATIONS }   -- used by the automated tests''')
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("english %d, locales %d, problems 0: wrote Locales.lua" % (len(english), len(tables)))
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
